import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import addFormats from 'ajv-formats';
import { format } from 'prettier';

const root = new URL('../', import.meta.url);
const schema = JSON.parse(await readFile(new URL('schemas/native-memory.schema.json', root), 'utf8'));
const definitions = ['SessionMetadata', 'SessionRead', 'SessionList', 'SessionCreated', 'VaultStatus'];
const generated = '// Generated by tools/generate-contracts.mjs. DO NOT EDIT.\n';
const types = generated + await compile({ $defs: schema.$defs,
  oneOf: definitions.map((name) => ({ $ref: '#/$defs/' + name })) }, 'NativeMemoryResult', {
  bannerComment: '', additionalProperties: false, maxItems: 0,
});
const ajv = new Ajv2020({ code: { source: true, esm: true }, strict: true });
addFormats(ajv, ['date-time']);
ajv.addSchema(schema);
const exports = {};
for (const name of definitions) {
  exports['validate' + name] = schema.$id + '#/$defs/' + name;
}
let validators = standaloneCode(ajv, exports);
// Ajv emits CommonJS runtime helper references even for ESM exports. Convert
// only the two inspected pinned helper modules to static browser imports.
const allowedHelpers = new Set(['ajv/dist/runtime/ucs2length', 'ajv-formats/dist/formats']);
const imports = new Map();
validators = validators.replace(/require\("([^"]+)"\)/g, (_, module) => {
  if (!allowedHelpers.has(module)) throw new Error('Unreviewed generated runtime helper: ' + module);
  if (!imports.has(module)) imports.set(module, 'runtime' + imports.size);
  const name = imports.get(module);
  // Node exposes CJS exports.default as a nested default, while Angular's
  // bundler unwraps __esModule. Normalize only this inspected helper shape.
  return module === 'ajv/dist/runtime/ucs2length'
    ? `({default:typeof ${name}.default === "function" ? ${name}.default : ${name}.default.default})`
    : name;
});
if (/\beval\s*\(|\bnew Function\b|\brequire\s*\(/.test(validators)) {
  throw new Error('Generated validators must not use runtime code evaluation or require.');
}
const validatorOutput = generated + '// @ts-nocheck -- generated standalone JavaScript validators.\n' +
  [...imports].map(([module, name]) => `import * as ${name} from '${module}.js';\n`).join('') + validators + '\n';
const outputs = [
  ['src/app/core/contracts.generated.ts', types],
  ['src/app/core/validators.generated.ts', await format(validatorOutput, { parser: 'typescript', singleQuote: true })],
];
for (const [path, output] of outputs) {
  const url = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8') !== output) throw new Error('Generated contract drift: ' + path);
  } else {
    await writeFile(url, output);
  }
  console.log((process.argv.includes('--check') ? 'Checked ' : 'Generated ') + fileURLToPath(url));
}
